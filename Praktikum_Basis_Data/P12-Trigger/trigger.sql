-- ============================================================
-- SOAL 1:
-- Buat trigger yang akan menyimpan data pegawai ke suatu tabel (buat tabel terlebih dahulu) jika ada data pegawai yang dihapus.
-- ============================================================

-- 1a. Buat tabel backup untuk menyimpan data pegawai yang dihapus Tabel ini punya kolom tambahan deleted_at untuk tracking kapan data dihapus. Struktur kolom mengikuti tabel EMPLOYEES dari OT sample schema.

CREATE TABLE deleted_employees (
    employee_id   NUMBER(6)             NOT NULL,
    first_name    VARCHAR2(20 BYTE),
    last_name     VARCHAR2(25 BYTE)     NOT NULL,
    email         VARCHAR2(25 BYTE)     NOT NULL,
    phone         VARCHAR2(20 BYTE),
    hire_date     DATE                  NOT NULL,
    manager_id    NUMBER(6),
    job_title     VARCHAR2(35 BYTE),
    deleted_at    DATE                  NOT NULL,
    deleted_by    VARCHAR2(128)
);


-- 1b. Buat trigger untuk backup data pegawai yang dihapus Pakai BEFORE DELETE supaya datanya siap sebelum benar-benar dihapus. FOR EACH ROW supaya bisa akses :OLD (data yang akan dihapus).

CREATE OR REPLACE TRIGGER trg_employees_delete_backup
BEFORE DELETE ON employees
FOR EACH ROW
BEGIN
    INSERT INTO deleted_employees (
        employee_id,
        first_name,
        last_name,
        email,
        phone,
        hire_date,
        manager_id,
        job_title,
        deleted_at,
        deleted_by
    ) VALUES (
        :OLD.employee_id,
        :OLD.first_name,
        :OLD.last_name,
        :OLD.email,
        :OLD.phone,
        :OLD.hire_date,
        :OLD.manager_id,
        :OLD.job_title,
        SYSDATE,                          -- waktu penghapusan
        USER                              -- username Oracle yang melakukan delete
    );
END;
/

-- 1c. Uji coba trigger Jalankan query berikut SATU PER SATU untuk verifikasi.

-- Lihat data pegawai yang ada
SELECT employee_id, first_name, last_name, email
FROM employees
WHERE employee_id = 100;

-- Hapus satu pegawai
DELETE FROM employees
WHERE employee_id = 100;

-- Cek apakah data tersimpan di tabel backup
SELECT * FROM deleted_employees;

-- ROLLBACK kalau cuma test (jangan commit)
ROLLBACK;

-- Cek apakah data tersimpan di tabel backup
SELECT * FROM deleted_employees;




-- 2a. Buat tabel untuk menyimpan riwayat perubahan harga Tambahkan kolom change_id sebagai PRIMARY KEY auto-increment (identity column) supaya setiap baris unik.

CREATE TABLE price_change (
    change_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    NUMBER(6)   NOT NULL,
    date_updated  DATE        NOT NULL,
    old_price     NUMBER(9,2),
    new_price     NUMBER(9,2)
);


-- 2b. Buat trigger untuk mencatat perubahan harga BEFORE UPDATE OF list_price artinya trigger cuma jalan kalau kolom LIST_PRICE ikut di-update (bukan kolom lain). Ini lebih efisien daripada trigger yg jalan tiap UPDATE.

CREATE OR REPLACE TRIGGER trg_products_price_change
BEFORE UPDATE OF list_price ON products
FOR EACH ROW
BEGIN
    IF :OLD.list_price != :NEW.list_price
       OR (:OLD.list_price IS NULL AND :NEW.list_price IS NOT NULL)
       OR (:OLD.list_price IS NOT NULL AND :NEW.list_price IS NULL)
    THEN
        INSERT INTO price_change (
            product_id,
            date_updated,
            old_price,
            new_price
        ) VALUES (
            :OLD.product_id,
            SYSDATE,
            :OLD.list_price,
            :NEW.list_price
        );
    END IF;
END;
/

-- 2c. Uji coba trigger Jalankan query berikut SATU PER SATU untuk verifikasi.

-- Lihat harga produk saat ini
SELECT product_id, product_name, list_price
FROM products
WHERE product_id = 1;

-- Update harga produk
UPDATE products
SET list_price = 999.99
WHERE product_id = 1;

-- Cek riwayat perubahan harga
SELECT * FROM price_change;

-- Kembalikan ke harga semula
UPDATE products
SET list_price = 640.99   -- ganti dengan harga asli
WHERE product_id = 1;

